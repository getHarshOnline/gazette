fn capture(root: &Path) -> CapturedSource {
    fn visit(
        root: &Path,
        directory: &Path,
        inventory: &mut InventoryBuilder,
        files: &mut BTreeMap<EntryPath, Vec<u8>>,
    ) {
        let mut entries: Vec<_> = fs::read_dir(directory)
            .expect("owned generated directory")
            .map(|entry| entry.expect("generated entry").path())
            .collect();
        entries.sort();
        for native in entries {
            let metadata = fs::symlink_metadata(&native).expect("native generated entry type");
            let path: EntryPath = native
                .strip_prefix(root)
                .expect("owned root")
                .to_str()
                .expect("fixture UTF-8 path")
                .replace(std::path::MAIN_SEPARATOR, "/")
                .parse()
                .expect("confined generated path");
            if metadata.is_dir() {
                inventory
                    .insert(path, Content::Directory)
                    .expect("directory inventory");
                visit(root, &native, inventory, files);
            } else {
                assert!(
                    metadata.is_file(),
                    "no generated symlinks or special files: {}",
                    native.display()
                );
                let bytes = fs::read(&native).expect("exact generated bytes");
                inventory
                    .insert(
                        path.clone(),
                        Content::File {
                            bytes: bytes.len() as u64,
                            sha256: Sha256Digest::of(&bytes),
                        },
                    )
                    .expect("bounded generated inventory");
                files.insert(path, bytes);
            }
        }
    }
    let mut inventory = InventoryBuilder::new(Limits::default());
    let mut files = BTreeMap::new();
    visit(root, root, &mut inventory, &mut files);
    CapturedSource::from_parts(inventory.finish(), files).expect("exact retained Rustdoc output")
}

fn assemble(input: &CapturedSource) -> Result<CapturedSource, gazette_core::documentation::Error> {
    assemble_reference(input, "fixture", "reference_fixture")
}

fn assemble_reference(
    input: &CapturedSource,
    project: &str,
    selected_crate: &str,
) -> Result<CapturedSource, gazette_core::documentation::Error> {
    Mintlify::new(&gazette_adapter_markdown::Comrak)
        .assemble_with_catalog(
            Request {
                name: "Native Rust reference",
                public_base_url: None,
                target: &Target::Mintlify {
                    theme: "mint".into(),
                    primary_color: "#123abc".into(),
                    light_color: None,
                    dark_color: None,
                    telemetry: None,
                },
                projects: &[ProjectModule {
                    slug: project,
                    title: "Fixture project",
                    manual: None,
                    navigation: vec![ProjectItem::Reference(Reference {
                        pages: None,
                        slug: "rust",
                        title: "Rust library",
                        artifact: Artifact {
                            format: Format::RustdocHtml,
                            tree: input.as_input(),
                            selection: &Selection::Directory {
                                path: Some(selected_crate.parse().expect("selected crate")),
                            },
                        },
                    })],
                }],
                usage: None,
            },
            Limits::default(),
            gazette_core::documentation::CatalogLimits::default(),
        )
        .map(|assembled| {
            let catalog = assembled
                .catalog
                .as_ref()
                .expect("Mintlify supplies validated catalog");
            let provider_pages = assembled
                .output
                .inventory()
                .entries()
                .iter()
                .filter(|entry| entry.path.as_str().ends_with(".mdx"))
                .count();
            assert_eq!(
                catalog.entries().len(),
                provider_pages,
                "native companions are not additional pages"
            );
            for entry in catalog.entries() {
                assert_eq!(entry.module, project);
                assert!(entry.title.as_ref().is_some_and(|title| !title.is_empty()));
                assert!(
                    entry
                        .body_text
                        .as_ref()
                        .is_some_and(|text| !text.is_empty())
                );
                let gazette_core::documentation::CatalogEvidence::Physical {
                    provider,
                    native_markdown: Some(native),
                } = &entry.evidence
                else {
                    panic!("Rustdoc page has both representations")
                };
                assert!(
                    assembled.output.file(provider).is_some()
                        && assembled.output.file(native).is_some()
                );
                assert_eq!(
                    provider.as_str().strip_suffix(".mdx"),
                    Some(entry.route.as_str())
                );
                assert_eq!(
                    native.as_str().strip_suffix(".md"),
                    Some(entry.route.as_str())
                );
            }
            assembled.output
        })
}

#[derive(Default)]
struct Observed {
    text: String,
    links: Vec<String>,
    anchors: BTreeSet<String>,
    tags: BTreeSet<String>,
}

struct Observe(RefCell<Observed>);
impl TokenSink for Observe {
    type Handle = ();
    fn process_token(&self, token: Token, _line: u64) -> TokenSinkResult<()> {
        let mut output = self.0.borrow_mut();
        match token {
            Token::CharacterTokens(value) => output.text.push_str(&value),
            Token::TagToken(tag) if tag.kind == TagKind::StartTag => {
                output.tags.insert(tag.name.to_string());
                for attribute in tag.attrs {
                    match attribute.name.local.as_ref() {
                        "href" => output.links.push(attribute.value.to_string()),
                        "id" => {
                            output.anchors.insert(attribute.value.to_string());
                        }
                        _ => {}
                    }
                }
            }
            _ => {}
        }
        TokenSinkResult::Continue
    }
}

fn observe(bytes: &[u8]) -> Observed {
    let text = std::str::from_utf8(bytes).expect("UTF-8 Markdown");
    let tokenizer = Tokenizer::new(
        Observe(RefCell::new(Observed::default())),
        Default::default(),
    );
    let queue = BufferQueue::default();
    queue.push_back(StrTendril::from_slice(text));
    let _ = tokenizer.feed(&queue);
    assert!(queue.is_empty(), "complete output inspected");
    tokenizer.end();
    tokenizer.sink.0.into_inner()
}

// The actual public target's body must survive the same native Markdown parse used
// by required disclosure. This does not invoke Gazette's authored HTML renderer.
fn observe_markdown(bytes: &[u8]) -> Observed {
    let source = std::str::from_utf8(bytes).expect("UTF-8 controlled Markdown");
    let document = gazette_adapter_markdown::Comrak
        .parse(
            source,
            gazette_core::markdown::Profile::PublicationMath,
            Default::default(),
        )
        .expect("actual emitted .md parses with the retained native Markdown adapter");
    let syntax = document.syntax();
    assert!(syntax.directives.is_empty());
    assert!(
        syntax.links.is_empty(),
        "references remain retained HTML attributes"
    );
    assert!(
        !syntax.html.is_empty(),
        "API content must not disappear into text"
    );
    let (_, body) = source
        .split_once("\n---\n\n")
        .expect("controlled emitter's unchanged frontmatter boundary");
    let mut remaining = body;
    for html in &syntax.html {
        let offset = remaining
            .find(html.literal.as_str())
            .expect("native HTML fact retains exact emitted bytes");
        assert!(
            remaining[..offset].trim().is_empty(),
            "only structural whitespace may be outside retained HTML facts"
        );
        remaining = &remaining[offset + html.literal.len()..];
    }
    assert!(
        remaining.trim().is_empty(),
        "complete API body is inspected"
    );
    observe(body.as_bytes())
}

fn page<'a>(tree: &'a CapturedSource, path: &str) -> &'a [u8] {
    tree.file(&path.parse().expect("expected page path"))
        .expect("expected generated page")
}

fn routes(value: &Value, output: &mut BTreeSet<String>) {
    match value {
        Value::String(path) => {
            output.insert(path.clone());
        }
        Value::Array(items) => {
            for item in items {
                routes(item, output);
            }
        }
        Value::Object(item) => routes(&item["pages"], output),
        _ => panic!("unsupported navigation shape"),
    }
}

fn generate(root: &Path, program: &Path) -> String {
    generate_source(root, program, LIBRARY)
}

fn generate_source(root: &Path, program: &Path, source: &str) -> String {
    fs::write(root.join("library.rs"), source).expect("owned Rust fixture");
    let version = Command::new(program)
        .arg("--version")
        .output()
        .expect("installed Rustdoc required; no silent skip");
    assert!(
        version.status.success(),
        "Rustdoc version failed: {}",
        String::from_utf8_lossy(&version.stderr)
    );
    let version = String::from_utf8(version.stdout).expect("Rustdoc version UTF-8");
    assert!(
        version.starts_with("rustdoc "),
        "unexpected native provider: {version}"
    );
    let generated = Command::new(program)
        .current_dir(root)
        .args([
            "library.rs",
            "--crate-name",
            "reference_fixture",
            "--crate-version",
            "0.1.0",
            "--edition",
            "2024",
            "-D",
            "warnings",
            "-o",
            "html",
        ])
        .output()
        .expect("execute installed native Rustdoc");
    assert!(
        generated.status.success(),
        "native generation failed ({version}): {}",
        String::from_utf8_lossy(&generated.stderr)
    );
    version
}

fn materialize(tree: &CapturedSource, root: &Path) {
    for entry in tree.inventory().entries() {
        let path = root.join(entry.path.as_str());
        match entry.content {
            Content::Directory => fs::create_dir_all(&path).expect("target directory"),
            Content::File { .. } => {
                fs::create_dir_all(path.parent().expect("target file parent"))
                    .expect("target parent");
                fs::write(&path, tree.file(&entry.path).expect("retained target file"))
                    .expect("materialize retained target file");
            }
        }
    }
}

