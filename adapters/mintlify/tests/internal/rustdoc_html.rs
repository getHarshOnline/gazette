#[test]
fn provider_literals_preserve_code_headings_and_native_markdown_bytes() {
    let source = document(
        "<pre><code>let x = &quot;quoted&quot;;\n\t&lt;T&gt; {}</code></pre><h4>Formatter&lt;'_&gt;</h4><p>Before\n<strong>bold</strong> after&nbsp;thin\u{2009}space.</p>",
        false,
    );
    let page = parse(source.as_bytes(), "literal fixture", 64 << 10).unwrap();
    let native = page
        .render("native", 64 << 10, &BTreeMap::new(), &BTreeMap::new())
        .unwrap();
    let expected = concat!(
        "---\ntitle: \"Record <T>\"\n---\n\n<p>Crate: <code>sample</code>; version: <code>0.1.0</code>; generated by Rustdoc <code>1.94.0 (qualified fixture)</code></p>\n\n",
        "<div id=\"main-content\"><h1>Record &lt;T&gt;\u{a0}</h1><pre><code>let x = \"quoted\";&#10;&#9;&lt;T&gt; &#123;&#125;</code></pre><h4>Formatter&lt;'&#95;&gt;</h4><p>Before&#10;<strong>bold</strong> after\u{a0}thin\u{2009}space.</p></div>\n"
    );
    assert_eq!(native, expected.as_bytes());
    let provider = page
        .render_provider("provider", 64 << 10, &BTreeMap::new(), &BTreeMap::new())
        .unwrap();
    let provider = String::from_utf8(provider).unwrap();
    assert!(provider.contains("</code></p> <div id=\"main-content\">"));
    assert!(!provider.contains("</code></p>\n\n"));
    assert!(
        provider
            .contains("<code><span children={\"let x = \\\"quoted\\\";\\n\\t<T> {}\"} /></code>"),
        "{provider}"
    );
    assert!(provider.contains("<h4><span children={\"Formatter<'_>\"} /></h4>"));
    assert!(provider.contains("<p>Before <strong>bold</strong> after\u{a0}thin\u{2009}space.</p>"));
    assert!(
        page.render_provider(
            "bounded",
            provider.len() - 1,
            &BTreeMap::new(),
            &BTreeMap::new()
        )
        .is_err()
    );
    assert_eq!(
        page.render("native", 64 << 10, &BTreeMap::new(), &BTreeMap::new())
            .unwrap(),
        native
    );
}

use super::parse;
use std::collections::BTreeMap;

fn document(body: &str, source: bool) -> String {
    let kind = if source { "src" } else { "struct" };
    let version = if source {
        ""
    } else {
        "<nav><span class=\"version\">0.1.0</span></nav>"
    };
    format!(
        "<!DOCTYPE html><html><head><meta name=\"generator\" content=\"rustdoc\"><meta name=\"rustdoc-vars\" data-current-crate=\"sample\" data-rustdoc-version=\"1.94.0 (qualified fixture)\"><script>const markup = '<section id=\"main-content\">';</script></head><body class=\"rustdoc {kind}\">{version}<main><section id=\"main-content\" class=\"content\"><h1>Record &lt;T&gt;&nbsp;<button id=\"copy-path\">Copy item path</button></h1>{body}</section></main></body></html>"
    )
}

#[test]
fn native_signature_structure_links_descriptions_and_reexport_are_retained() {
    let html = document(
        concat!(
            "<pre class=\"rust item-decl\"><code>pub fn take&lt;T: <a href=\"trait.Display.html\">Display</a>&gt;(v: &amp;T) -&gt; T {\n    *v\n}</code></pre>",
            "<details class=\"toggle\" open><summary><section id=\"method.take\"><h4 class=\"code-header\">fn take(&amp;self)</h4></section></summary><div class=\"docblock\"><p>Original docs.</p></div></details>",
            "<dl><dt id=\"reexport.PublicRecord\"><code>pub use Record as PublicRecord;</code></dt></dl>",
            "<script src=\"../trait.impl/sample/trait.Record.js\" async></script>"
        ),
        false,
    );
    let page = parse(html.as_bytes(), "fixture", 64 << 10).expect("native profile");
    assert_eq!(page.title, "Record <T>");
    assert_eq!(page.crate_name, "sample");
    assert_eq!(page.version.as_deref(), Some("0.1.0"));
    assert_eq!(page.generator, "1.94.0 (qualified fixture)");
    assert_eq!(
        page.semantic_scripts,
        ["../trait.impl/sample/trait.Record.js"]
    );
    assert!(page.anchors.contains("reexport.PublicRecord"));
    assert!(page.anchors.contains("method.take"));
    assert_eq!(page.links().collect::<Vec<_>>(), ["trait.Display.html"]);
    let links = BTreeMap::from([("trait.Display.html".into(), "/rust/trait.Display".into())]);
    let output = page
        .render("fixture", 64 << 10, &links, &BTreeMap::new())
        .expect("bounded Markdown/HTML");
    let text = std::str::from_utf8(&output).expect("UTF-8");
    assert!(text.contains("pub fn take&lt;T: <a href=\"/rust/trait.Display\">Display</a>&gt;(v: &amp;T) -&gt; T &#123;&#10;    &#42;v&#10;&#125;"));
    assert!(text.contains("fn take(&amp;self)"));
    assert!(text.contains("Original docs."));
    assert!(text.contains("pub use Record as PublicRecord;"));
    assert!(!text.contains("<script"));
    assert!(!text.contains("Copy item path"));
    assert!(!text.contains("<details"));
}

#[test]
fn native_item_kinds_reuse_page_links_and_markdown_html_emission() {
    for (kind, declaration, expected) in [
        (
            "constant",
            "pub const MAX: usize = 8;",
            "pub const MAX: usize = 8;",
        ),
        (
            "static",
            "pub static LABEL: &amp;str = &quot;reference&quot;;",
            "pub static LABEL: &amp;str = \"reference\";",
        ),
        (
            "macro",
            "macro_rules! record { ($value:expr) =&gt; { ... }; }",
            "macro&#95;rules&#33; record &#123; (&#36;value:expr) =&gt; &#123; ... &#125;; &#125;",
        ),
        (
            "union",
            "pub union Word { pub integer: u32, pub floating: f32, }",
            "pub union Word &#123; pub integer: u32, pub floating: f32, &#125;",
        ),
    ] {
        let html = document(&format!(
            "<pre class=\"rust item-decl\"><code>{declaration}</code></pre><div class=\"docblock\"><p id=\"meaning\">Original value contract; see <a href=\"constant.OTHER.html\">OTHER</a>.</p></div>"
        ), false).replace("class=\"rustdoc struct\"", &format!("class=\"rustdoc {kind}\""));
        let page = parse(html.as_bytes(), kind, 64 << 10).expect("native value-item envelope");
        assert!(!page.source);
        assert!(page.anchors.contains("meaning"));
        assert_eq!(page.links().collect::<Vec<_>>(), ["constant.OTHER.html"]);
        let links = BTreeMap::from([("constant.OTHER.html".into(), "/rust/constant.OTHER".into())]);
        let output = page
            .render(kind, 64 << 10, &links, &BTreeMap::new())
            .expect("same bounded emitter");
        let text = std::str::from_utf8(&output).unwrap();
        assert!(text.contains(expected), "{kind}: {text}");
        assert!(
            text.contains(
                "Original value contract; see <a href=\"/rust/constant.OTHER\">OTHER</a>."
            )
        );
        assert!(page.render(kind, 8, &links, &BTreeMap::new()).is_err());
        assert!(
            parse(
                html.replace(kind, "unrecognized-item").as_bytes(),
                "unknown kind",
                64 << 10
            )
            .is_err()
        );
    }
}

#[test]
fn source_lines_keep_code_without_gutter_text_and_accept_parent_bound_ranges() {
    let html = document(
        "<pre class=\"rust\"><code><a href=#1 id=1 data-nosnippet>1</a>pub fn a() {}\n<a href=#2 id=2 data-nosnippet>2</a>// next\n</code></pre>",
        true,
    );
    let page = parse(html.as_bytes(), "source", 64 << 10).expect("source page");
    assert!(page.source);
    assert!(page.version.is_none());
    assert_eq!(page.links().count(), 0);
    let ranges = BTreeMap::from([("1".into(), vec!["1-2".into()])]);
    let text = String::from_utf8(
        page.render("source", 64 << 10, &BTreeMap::new(), &ranges)
            .expect("source Markdown/HTML"),
    )
    .expect("UTF-8");
    assert!(text.contains("<span id=\"1-2\"></span><span id=\"1\"></span>pub fn a() &#123;&#125;&#10;<span id=\"2\"></span>// next&#10;"));
    assert!(!text.contains(">1</span>"));
    assert!(
        parse(
            document(
                "<pre><code><a href=#1 id=1 data-nosnippet>unexpected code</a></code></pre>",
                true
            )
            .as_bytes(),
            "invalid source marker",
            64 << 10
        )
        .is_err()
    );
    assert!(
        page.render(
            "source",
            64 << 10,
            &BTreeMap::new(),
            &BTreeMap::from([("7".into(), vec!["7-8".into()])])
        )
        .is_err()
    );
}

