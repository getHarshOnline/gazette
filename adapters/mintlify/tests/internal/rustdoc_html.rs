#[test]
fn malformed_identity_anchors_nesting_and_controls_refuse_complete_page() {
    for body in [
        "<div id=\"same\"></div><p id=\"same\">duplicate</p>",
        "<div><p>bad</div></p>",
        "<div id=\"main-content\"></div>",
        "<p id=\"bad anchor\">text</p>",
        "<p title=\"one\" title=\"two\">text</p>",
        "<h1>second heading</h1>",
        "<p>bad\0</p>",
    ] {
        assert!(parse(document(body, false).as_bytes(), "invalid", 64 << 10).is_err());
    }
    let html = document("<p>complete</p>", false);
    assert!(parse(&html.as_bytes()[..html.len() - 7], "truncated", 64 << 10).is_err());
    assert!(
        parse(
            html.replace("content=\"rustdoc\"", "content=\"other\"")
                .as_bytes(),
            "identity",
            64 << 10
        )
        .is_err()
    );
    assert!(
        parse(
            document(&"<div>".repeat(129), false).as_bytes(),
            "deep",
            64 << 10
        )
        .is_err()
    );
}

#[test]
fn missing_link_bindings_and_input_output_limits_never_return_partial_output() {
    let html = document("<p><a href=\"fn.other.html#example\">other</a></p>", false);
    assert!(parse(html.as_bytes(), "limit", html.len() - 1).is_err());
    let page = parse(html.as_bytes(), "fixture", 64 << 10).expect("page");
    assert!(
        page.render("fixture", 64 << 10, &BTreeMap::new(), &BTreeMap::new())
            .is_err()
    );
    let links = BTreeMap::from([(
        "fn.other.html#example".into(),
        "/sample/fn.other#example".into(),
    )]);
    assert!(page.render("limit", 8, &links, &BTreeMap::new()).is_err());
    assert!(
        page.render("fixture", 64 << 10, &links, &BTreeMap::new())
            .is_ok()
    );
}

#[test]
fn html_control_characters_remain_text_not_expressions_or_markdown() {
    let html = document(
        "<p title=\"&quot;{attribute}&quot;\">{call()} &lt;T&gt; *literal* _name_ `code` [label] \\ $value</p>",
        false,
    );
    let page = parse(html.as_bytes(), "escape", 64 << 10).expect("page");
    let output = String::from_utf8(
        page.render("escape", 64 << 10, &BTreeMap::new(), &BTreeMap::new())
            .expect("escaped output"),
    )
    .expect("UTF-8");
    assert!(output.contains("title=\"&quot;&#123;attribute&#125;&quot;\""));
    assert!(output.contains("&#123;call()&#125; &lt;T&gt; &#42;literal&#42; &#95;name&#95; &#96;code&#96; &#91;label&#93; &#92; &#36;value"));
}

#[test]
fn native_main_section_focus_control_does_not_expand_attribute_admission() {
    let original = document("<p>Original explanation.</p>", false);
    let native = original.replace("id=\"main-content\"", "id=\"main-content\" tabindex=\"-1\"");
    let plain = parse(original.as_bytes(), "native", 64 << 10).unwrap();
    let focused = parse(native.as_bytes(), "native", 64 << 10).unwrap();
    assert_eq!(
        plain
            .render("native", 64 << 10, &BTreeMap::new(), &BTreeMap::new())
            .unwrap(),
        focused
            .render("native", 64 << 10, &BTreeMap::new(), &BTreeMap::new())
            .unwrap(),
    );
    for changed in [
        native.replace("tabindex=\"-1\"", "tabindex=\"0\""),
        original.replace("<p>", "<p tabindex=\"-1\">"),
        original
            .replace("<p>", "<section id=\"other\" tabindex=\"-1\">")
            .replace("</p>", "</section>"),
    ] {
        assert!(parse(changed.as_bytes(), "native", 64 << 10).is_err());
    }
}
