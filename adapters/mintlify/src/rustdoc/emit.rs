//! Controlled Markdown with inert HTML from admitted native structure; links are caller-resolved.

use super::html::{Node, Page};
use crate::{Error, invalid};
use std::collections::{BTreeMap, BTreeSet};

struct Writer<'a> {
    context: &'a str,
    maximum: usize,
    bytes: Vec<u8>,
    provider: bool,
}

impl Writer<'_> {
    fn text(&mut self, text: &str, protected: bool) -> Result<(), Error> {
        if !self.provider {
            return self.escape(text, false);
        }
        if protected {
            self.push("<span children={")?;
            let mut literal = crate::output::BoundedBuffer::new(
                self.maximum.saturating_sub(self.bytes.len()) as u64,
            );
            serde_json::to_writer(&mut literal, text)
                .map_err(|_| invalid(self.context, "Rustdoc literal output ceiling exceeded"))?;
            let bytes = literal.finish();
            self.push(std::str::from_utf8(&bytes).expect("JSON is UTF-8"))?;
            return self.push("} />");
        }
        let mut whitespace = false;
        for character in text.chars() {
            if matches!(character, ' ' | '\t' | '\r' | '\n' | '\u{000c}') {
                if !whitespace {
                    self.push(" ")?;
                }
                whitespace = true;
            } else {
                whitespace = false;
                self.escape(character.encode_utf8(&mut [0; 4]), false)?;
            }
        }
        Ok(())
    }

    fn push(&mut self, text: &str) -> Result<(), Error> {
        if self
            .bytes
            .len()
            .checked_add(text.len())
            .is_none_or(|size| size > self.maximum)
        {
            return Err(invalid(
                self.context,
                "Rustdoc Markdown output ceiling exceeded",
            ));
        }
        self.bytes.extend_from_slice(text.as_bytes());
        Ok(())
    }

    fn escape(&mut self, text: &str, attribute: bool) -> Result<(), Error> {
        for character in text.chars() {
            let mut buffer = [0; 4];
            self.push(match character {
                '&' => "&amp;",
                '<' => "&lt;",
                '>' => "&gt;",
                '{' => "&#123;",
                '}' => "&#125;",
                '*' => "&#42;",
                '_' => "&#95;",
                '`' => "&#96;",
                '[' => "&#91;",
                ']' => "&#93;",
                '\\' => "&#92;",
                '!' => "&#33;",
                '~' => "&#126;",
                '$' => "&#36;",
                '|' => "&#124;",
                '#' => "&#35;",
                '"' if attribute => "&quot;",
                '\'' if attribute => "&#39;",
                '\n' => "&#10;",
                '\r' => "&#13;",
                '\t' => "&#9;",
                character if character.is_control() => {
                    return Err(invalid(
                        self.context,
                        "unsupported control in Rustdoc content",
                    ));
                }
                character => character.encode_utf8(&mut buffer),
            })?;
        }
        Ok(())
    }
}

pub(super) fn render(
    page: &Page,
    nodes: &[Node],
    context: &str,
    maximum: usize,
    links: &BTreeMap<String, String>,
    extra_ids: &BTreeMap<String, Vec<String>>,
    provider: bool,
) -> Result<Vec<u8>, Error> {
    let mut anchors = page.anchors.clone();
    for (line, ranges) in extra_ids {
        if !page.source || !page.anchors.contains(line) {
            return Err(invalid(
                context,
                "extra Rustdoc anchor has no source-line owner",
            ));
        }
        for range in ranges {
            if range.is_empty()
                || range.chars().any(|c| c.is_control() || c.is_whitespace())
                || !anchors.insert(range.clone())
            {
                return Err(invalid(
                    context,
                    "invalid or duplicate extra Rustdoc anchor",
                ));
            }
        }
    }
    let mut output = Writer {
        context,
        maximum,
        bytes: Vec::new(),
        provider,
    };
    let title = serde_json::to_string(&page.title)
        .map_err(|_| invalid(context, "cannot encode Rustdoc title"))?;
    output.push("---\ntitle: ")?;
    output.push(&title)?;
    output.push("\n---\n\n<p>Crate: <code>")?;
    output.text(&page.crate_name, true)?;
    output.push("</code>")?;
    if let Some(version) = &page.version {
        output.push("; version: <code>")?;
        output.text(version, true)?;
        output.push("</code>")?;
    }
    output.push("; generated by Rustdoc <code>")?;
    output.text(&page.generator, true)?;
    output.push(if provider {
        "</code></p> "
    } else {
        "</code></p>\n\n"
    })?;
    let mut used = BTreeSet::new();
    let mut protected = 0usize;
    let mut math = false;
    for node in nodes {
        match node {
            Node::Text(text) if math => output.escape(text, false)?,
            Node::Text(text) => output.text(text, protected != 0)?,
            Node::End(name) => {
                if name == "math" {
                    math = false;
                }
                if protects_text(name) {
                    protected -= 1;
                }
                output.push("</")?;
                output.push(name)?;
                output.push(">")?;
            }
            Node::Start { name, attributes } => {
                if name == "math" {
                    math = true;
                }
                if protects_text(name) {
                    protected += 1;
                }
                if let Some(ids) = attributes.get("id").and_then(|id| extra_ids.get(id)) {
                    for id in ids {
                        output.push("<span id=\"")?;
                        output.escape(id, true)?;
                        output.push("\"></span>")?;
                    }
                }
                output.push("<")?;
                output.push(name)?;
                for (key, original) in attributes {
                    let value = if key == "href" {
                        used.insert(original.as_str());
                        links
                            .get(original)
                            .filter(|value| {
                                !value.is_empty() && !value.chars().any(char::is_control)
                            })
                            .ok_or_else(|| {
                                invalid(context, "Rustdoc reference has no validated target")
                            })?
                    } else {
                        original
                    };
                    output.push(" ")?;
                    output.push(key)?;
                    output.push("=\"")?;
                    output.escape(value, true)?;
                    output.push("\"")?;
                }
                output.push(if matches!(name.as_str(), "br" | "hr" | "wbr") {
                    " />"
                } else {
                    ">"
                })?;
            }
        }
    }
    if used.len() != page.links().count() {
        return Err(invalid(context, "incomplete Rustdoc reference projection"));
    }
    output.push("\n")?;
    Ok(output.bytes)
}

fn protects_text(name: &str) -> bool {
    matches!(
        name,
        "pre" | "code" | "h1" | "h2" | "h3" | "h4" | "h5" | "h6"
    )
}
