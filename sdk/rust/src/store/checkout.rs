//! Configure a local output repository before binding its existing journal-owned output plan.

use super::Writer;
use crate::{build, release, source};
use std::path::{Path, PathBuf};

/// The original metadata result and output plan, retained together before materialization.
pub struct CheckoutMaterialization<'a> {
    /// Independently verified repository metadata; does not grant output ownership.
    pub checkout: release::OutputCheckoutReport,
    /// Existing journal-owned materialization plan over the same native root/.git identities.
    pub plan: build::MaterializationPlan<'a>,
}

/// Setup and later output-planning failures retain their different effect evidence.
#[derive(Debug)]
pub enum CheckoutMaterializationError {
    /// Configuration or native coordinate refused before setup effects.
    Selection(&'static str),
    /// Existing held journal custody refused before setup effects.
    Store(super::Error),
    /// Native metadata may remain; inspect its explicit effect before continuing.
    Setup(release::RepositorySetupError),
    /// Existing output rules refused; a completed metadata setup is retained when present.
    Plan {
        /// Original output planner refusal.
        error: Box<build::MaterializationError>,
        /// Completed metadata setup, if it preceded the planner refusal.
        checkout: Option<release::OutputCheckoutReport>,
    },
}
impl std::fmt::Display for CheckoutMaterializationError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Selection(reason) => f.write_str(reason),
            Self::Store(e) => e.fmt(f),
            Self::Setup(e) => e.fmt(f),
            Self::Plan { error, .. } => error.fmt(f),
        }
    }
}
impl std::error::Error for CheckoutMaterializationError {}

impl Writer {
    /// Acquire the configured site's exact remote parent while protecting actual held custody.
    /// The destination comes from the retained workspace; no duplicate remote is accepted.
    ///
    /// # Errors
    /// Refuses pending materialization or unsafe roots; retains partial acquisition evidence.
    #[allow(clippy::too_many_arguments)]
    pub fn acquire_configured_parent(
        &mut self,
        rendered: &build::PublicationRender<'_>,
        git: &release::GitSelection,
        history_root: &Path,
        expected: &source::CommitId,
        protected: &[PathBuf],
        options: release::ParentAcquisitionOptions,
    ) -> Result<release::ParentAcquisitionReport, CheckoutMaterializationError> {
        let (root, destination, mut protected) = self.checkout_selection(rendered, protected)?;
        protected.push(root);
        let release::PublicationDestination::Git { remote, branch } = destination;
        release::acquire_parent(
            git,
            release::ParentAcquisitionRequest {
                root: history_root,
                remote: &remote,
                branch: &branch,
                expected,
                protected_roots: &protected,
            },
            options,
        )
        .map_err(CheckoutMaterializationError::Setup)
    }

    /// Set up configured metadata and then use the existing completed-history output planner.
    /// No generated bytes are written here. Unrelated files remain unowned, and an existing
    /// materialization's root/.git identity cannot be silently replaced or upgraded.
    ///
    /// # Errors
    /// Refuses pending history, unsafe setup, divergent refs and existing output conflicts.
    /// A failure after metadata setup returns that completed setup alongside the refusal.
    #[allow(clippy::too_many_arguments)]
    pub fn plan_materialization_with_checkout<'a>(
        &mut self,
        rendered: &'a build::PublicationRender<'_>,
        expected: &release::OutputCheckoutState,
        parent: Option<&release::OutputCheckoutParent>,
        protected: &[PathBuf],
        options: release::OutputCheckoutOptions,
        limits: source::Limits,
        evidence_bytes: usize,
    ) -> Result<CheckoutMaterialization<'a>, CheckoutMaterializationError> {
        let (root, destination, protected) = self.checkout_selection(rendered, protected)?;
        let frontier = self
            .inspect_materialization(&root)
            .map_err(CheckoutMaterializationError::Store)?
            .frontier;
        let prior = if let Some(record) = &frontier.head {
            if record.intent.binding.administration().is_none()
                || matches!(expected, release::OutputCheckoutState::Missing)
            {
                return Err(CheckoutMaterializationError::Selection(
                    "existing output history cannot acquire a different Git identity",
                ));
            }
            let plan = self
                .plan_materialization(rendered, &protected, limits, evidence_bytes)
                .map_err(|error| CheckoutMaterializationError::Plan {
                    error: Box::new(error),
                    checkout: None,
                })?;
            Some(plan.output().binding().clone())
        } else {
            None
        };
        let checkout = release::prepare_output_checkout(
            release::OutputCheckoutRequest {
                root: &root,
                destination: &destination,
                expected,
                parent,
                protected_roots: &protected,
            },
            options,
        )
        .map_err(CheckoutMaterializationError::Setup)?;
        if prior
            .as_ref()
            .is_some_and(|binding| *binding != checkout.binding)
        {
            return Err(CheckoutMaterializationError::Setup(
                release::RepositorySetupError {
                    reason: "output identity changed during repository setup",
                    effect: release::RepositorySetupEffect::LocalStateMayRemain,
                    cleanup: None,
                },
            ));
        }
        match self.plan_materialization(rendered, &protected, limits, evidence_bytes) {
            Ok(plan) if plan.output().binding() == &checkout.binding => {
                Ok(CheckoutMaterialization { checkout, plan })
            }
            Ok(_) => Err(CheckoutMaterializationError::Setup(
                release::RepositorySetupError {
                    reason: "output identity changed before materialization planning",
                    effect: release::RepositorySetupEffect::LocalStateMayRemain,
                    cleanup: None,
                },
            )),
            Err(error) => Err(CheckoutMaterializationError::Plan {
                error: Box::new(error),
                checkout: Some(checkout),
            }),
        }
    }

    pub(super) fn checkout_selection(
        &mut self,
        rendered: &build::PublicationRender<'_>,
        protected: &[PathBuf],
    ) -> Result<
        (PathBuf, release::PublicationDestination, Vec<PathBuf>),
        CheckoutMaterializationError,
    > {
        if rendered.preview_urls().is_some() {
            return Err(CheckoutMaterializationError::Selection(
                "preview output cannot initialize a configured checkout",
            ));
        }
        let selected = rendered
            .inputs()
            .output_directory()
            .map_err(|_| {
                CheckoutMaterializationError::Selection("output coordinate is unresolved")
            })?
            .ok_or(CheckoutMaterializationError::Selection(
                "output directory is unconfigured",
            ))?;
        let parent = selected
            .parent()
            .and_then(|path| std::fs::canonicalize(path).ok())
            .ok_or(CheckoutMaterializationError::Selection(
                "output parent must exist",
            ))?;
        let root = parent.join(selected.file_name().ok_or(
            CheckoutMaterializationError::Selection("output name is missing"),
        )?);
        let destination = rendered
            .inputs()
            .compilation()
            .workspace
            .destination(rendered.inputs().site())
            .cloned()
            .ok_or(CheckoutMaterializationError::Selection(
                "output Git destination is unconfigured",
            ))?;
        let mut all = rendered.protected_roots().to_vec();
        all.extend_from_slice(protected);
        all.extend(
            self.0
                .materialization_protected_roots()
                .map_err(CheckoutMaterializationError::Store)?,
        );
        all.sort();
        all.dedup();
        let frontier = self
            .inspect_materialization(&root)
            .map_err(CheckoutMaterializationError::Store)?
            .frontier;
        if frontier.root != root {
            return Err(CheckoutMaterializationError::Store(
                super::Error::MaterializationVerification,
            ));
        }
        if frontier.active.is_some() {
            return Err(CheckoutMaterializationError::Store(
                super::Error::MaterializationPending,
            ));
        }
        Ok((root, destination, all))
    }
}
