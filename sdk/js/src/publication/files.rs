//! Owned byte delivery from the existing complete native render, without staging or rereads.

use gazette_sdk::source::{CapturedSource, Content};
use napi::{Result, bindgen_prelude::Uint8Array};
use napi_derive::napi;

use super::{RenderOptions, with_rendered};
use crate::transport;

/// One generated regular file; directory entries remain in the native report inventory.
#[napi(object)]
pub struct PublicationFile {
    /// Exact confined output path, not a filesystem destination or URL.
    pub path: String,
    /// Owned binary bytes; host changes do not modify retained native inputs.
    pub bytes: Uint8Array,
}

/// Complete regular-file payloads for one explicitly selected site, in native path order.
#[napi(object)]
pub struct PublicationSiteFiles {
    /// Original site identity, never inferred from a filename.
    pub site: String,
    /// Every generated regular file, including binary assets and machine outputs.
    pub files: Vec<PublicationFile>,
}

/// A complete private local render and the exact bytes described by its native inventory.
#[napi(object)]
pub struct PublicationFiles {
    /// Unmodified native inspection JSON; includes directories, sizes and exact digests.
    pub report: String,
    /// Complete requested membership in native identity order; never a successful subset.
    pub sites: Vec<PublicationSiteFiles>,
}

/// Deliver generated bytes through the shared local Rust SDK without filesystem writes.
/// Native aggregate output bounds cover payloads; `resultBytes` bounds report JSON.
/// This is private local rendering, not publication admission or certification.
///
/// # Errors
/// Uses the same permission, input, limit and complete-set failure contract as `renderSites`.
/// Refuses missing native payloads instead of returning an incomplete file list.
#[napi]
pub fn render_site_files(bytes: Uint8Array, options: RenderOptions) -> Result<PublicationFiles> {
    with_rendered(bytes, options, |rendered, report| {
        let sites = rendered
            .sites()
            .iter()
            .map(|(site, result)| {
                let output = result
                    .as_ref()
                    .map_err(|_| transport("node_output_contract"))?
                    .site()
                    .output();
                let files = file_payloads(output)?;
                Ok(PublicationSiteFiles {
                    site: site.to_string(),
                    files,
                })
            })
            .collect::<Result<Vec<_>>>()?;
        Ok(PublicationFiles { report, sites })
    })
}

pub(crate) fn file_payloads(output: &CapturedSource) -> Result<Vec<PublicationFile>> {
    output
        .inventory()
        .entries()
        .iter()
        .filter(|entry| matches!(entry.content, Content::File { .. }))
        .map(|entry| {
            let bytes = output
                .file(&entry.path)
                .ok_or_else(|| transport("node_output_contract"))?;
            Ok(PublicationFile {
                path: entry.path.to_string(),
                bytes: Uint8Array::new(bytes.to_vec()),
            })
        })
        .collect()
}
