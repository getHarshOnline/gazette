//! Complete retained output sets use one held native writer and real destination trees.

use std::{collections::BTreeMap, path::Path};

use gazette_sdk::workspace::Key;

use super::super::{OTHER, sites};
use super::{
    Fixture, PAGE, build, bytes, fs, initialize, options, session, source, tempdir, writer,
};

const SELECTED: [&str; 2] = ["site:one", "site:other"];
const THREE: [&str; 3] = ["site:one", "site:other", "site:z-last"];
const LAST: &str = "+++\n[content]\nid='content:last'\nsite='site:z-last'\ntitle='Last independent page'\nlifecycle='published'\nroute={path='/last/'}\nstructure={kind='page',family={kind='documentation'}}\n+++\n# Retained last body\n";

fn key(value: &str) -> Key {
    value.parse().expect("exact publication identity")
}

fn ids(selected: &[&str], generation: &str) -> BTreeMap<Key, source::Sha256Digest> {
    selected
        .iter()
        .map(|site| {
            (
                key(site),
                source::Sha256Digest::of(format!("{generation}:{site}").as_bytes()),
            )
        })
        .collect()
}

fn destinations(config: &str, selected: &[(&str, &Path)]) -> String {
    let mut configured = config.to_owned();
    for (site, root) in selected {
        let needle = format!("site='{site}'\npublic_base_url");
        assert_eq!(configured.matches(&needle).count(), 1);
        configured = configured.replacen(
            &needle,
            &format!(
                "site='{site}'\noutput={{directory={:?}}}\npublic_base_url",
                root.to_str().expect("native destination coordinate")
            ),
            1,
        );
    }
    configured
}

fn render_set<'a>(
    acquired: &'a build::AcquiredPublicationSet,
    selected: &[&str],
) -> build::RenderedPublicationSet<'a> {
    let page = "page.html".parse().expect("page entry");
    let alias = "alias.html".parse().expect("alias entry");
    let model = "model.json".parse().expect("explicit private model entry");
    build::render_publications(
        acquired,
        sites::options(selected, &page, &alias, &model),
        Default::default(),
    )
    .expect("one retained native render phase")
}

fn snapshot(root: &Path) -> source::TreeIdentity {
    source::inspect(root, None, Default::default())
        .expect("actual complete native tree")
        .identity()
}

fn output_root(root: &Path, pointer: bool) {
    fs::create_dir_all(root).expect("existing configured destination");
    fs::write(root.join("user.txt"), b"independent owner bytes").expect("user sentinel");
    if pointer {
        fs::write(root.join(".git"), b"gitdir: ../owner-admin\n").expect("Git pointer");
    } else {
        let _repository = git2::Repository::init(root).expect("actual Git administration");
    }
}

fn assert_generated(rendered: &build::PublicationRender<'_>, root: &Path) {
    for entry in rendered.site().output().inventory().entries() {
        match entry.content {
            source::Content::Directory => assert!(root.join(entry.path.as_str()).is_dir()),
            source::Content::File { .. } => assert_eq!(
                fs::read(root.join(entry.path.as_str())).expect("native generated bytes"),
                bytes(rendered.site().output(), entry.path.as_str()),
                "exact retained output {}",
                entry.path
            ),
        }
    }
}

fn assert_unowned(current: &mut gazette_sdk::store::Writer, roots: &[&Path]) {
    for root in roots {
        let history = current
            .inspect_materialization(&fs::canonicalize(root).expect("canonical destination"))
            .expect("actual held journal frontier");
        assert!(history.frontier.head.is_none());
        assert!(history.frontier.active.is_none());
    }
}

#[test]
fn two_site_completed_history_survives_writer_reopen_without_imported_receipts() {
    let fixture = Fixture::new(&[]);
    let parent = tempdir().expect("disjoint native outputs");
    let roots = [parent.path().join("one"), parent.path().join("other")];
    output_root(&roots[0], false);
    output_root(&roots[1], true);
    let git = snapshot(&roots[0].join(".git"));
    let config = destinations(
        &fixture.config(),
        &[(SELECTED[0], &roots[0]), (SELECTED[1], &roots[1])],
    );
    let acquired = sites::acquire_set(&config, &SELECTED);
    let rendered = render_set(&acquired, &SELECTED);
    assert!(rendered.is_complete());
    let (journal, initial) = initialize();
    let mut first = writer(journal.path(), initial.header);
    let before = snapshot(parent.path());
    let plan = first
        .plan_materializations(&rendered, Default::default(), options().evidence_bytes)
        .expect("all destinations and histories before any append");
    let replay = first
        .plan_materializations(&rendered, Default::default(), options().evidence_bytes)
        .expect("second original plan, not reconstructed historical input");
    assert_eq!(
        plan.sites().keys().cloned().collect::<Vec<_>>(),
        SELECTED.map(key)
    );
    assert!(plan.sites().values().all(|plan| plan.previous().is_none()));
    assert_eq!(snapshot(parent.path()), before);
    assert_unowned(&mut first, &[&roots[0], &roots[1]]);
    let first_ids = ids(&SELECTED, "first");
    let results = first
        .materialize_set(plan, &first_ids, options())
        .expect("actual two-site intent/write/read-back/completion");
    assert_eq!(
        results.keys().cloned().collect::<Vec<_>>(),
        SELECTED.map(key)
    );
    for (site, root) in SELECTED.into_iter().zip(&roots) {
        let result = &results[&key(site)];
        assert!(result.history.inserted);
        assert_eq!(result.history.record.intent.id, first_ids[&key(site)]);
        assert!(result.history.record.completion.is_some());
        let output = result
            .output
            .as_ref()
            .expect("actual current native result");
        assert_eq!(
            output.generated(),
            rendered.sites()[&key(site)]
                .as_ref()
                .unwrap()
                .site()
                .output()
                .inventory()
        );
        assert_eq!(output.inventory(), &result.history.record.intent.expected);
        assert_generated(rendered.sites()[&key(site)].as_ref().unwrap(), root);
    }
    let after = snapshot(parent.path());
    let historical = first
        .materialize_set(replay, &first_ids, options())
        .expect("equal original intents return historical results without FS dispatch");
    assert!(
        historical
            .values()
            .all(|result| !result.history.inserted && result.output.is_none())
    );
    assert_eq!(snapshot(parent.path()), after);
    let expected = first.inspect().expect("original held coordinates").header;
    first.close().expect("explicit original writer close");
    for site in SELECTED {
        let history = gazette_sdk::store::inspect_materialization(
            &initial.database,
            results[&key(site)]
                .output
                .as_ref()
                .unwrap()
                .binding()
                .canonical_root(),
            Some(&expected),
            session().read,
        )
        .expect("independent persisted completion after close");
        assert_eq!(
            history.frontier.head.unwrap().intent.id,
            first_ids[&key(site)]
        );
        assert!(history.frontier.active.is_none());
    }
    drop(results);
    drop(historical); // Later ownership must come from the journal, not these native receipts.
    let page = PAGE
        .replace("aliases=['/old.html']", "aliases=[]")
        .replace("**Retained** body", "**Second** body");
    let other = OTHER.replace("# Other body", "# Second other body");
    let changed = Fixture::new(&[
        ("one/page.md", page.as_bytes()),
        ("other/page.md", other.as_bytes()),
    ]);
    let config = destinations(
        &changed.config(),
        &[(SELECTED[0], &roots[0]), (SELECTED[1], &roots[1])],
    );
    let acquired = sites::acquire_set(&config, &SELECTED);
    let changed_render = render_set(&acquired, &SELECTED);
    let mut second = writer(journal.path(), expected);
    let plan = second
        .plan_materializations(
            &changed_render,
            Default::default(),
            options().evidence_bytes,
        )
        .expect("independently observed bytes plus stored completed ownership");
    for site in SELECTED {
        assert_eq!(
            plan.sites()[&key(site)].previous(),
            Some(first_ids[&key(site)])
        );
    }
    assert!(
        plan.sites()[&key(SELECTED[0])]
            .output()
            .changes()
            .iter()
            .any(|change| change.path.as_str() == "old.html" && change.after.is_none())
    );
    let second_ids = ids(&SELECTED, "second");
    let results = second
        .materialize_set(plan, &second_ids, options())
        .expect("new complete generation");
    for (site, root) in SELECTED.into_iter().zip(&roots) {
        assert_eq!(
            results[&key(site)].history.record.intent.previous,
            Some(first_ids[&key(site)])
        );
        assert!(results[&key(site)].output.is_some());
        assert_generated(changed_render.sites()[&key(site)].as_ref().unwrap(), root);
        assert_eq!(
            fs::read(root.join("user.txt")).unwrap(),
            b"independent owner bytes"
        );
        let head = second
            .inspect_materialization(
                results[&key(site)]
                    .output
                    .as_ref()
                    .unwrap()
                    .binding()
                    .canonical_root(),
            )
            .unwrap()
            .frontier
            .head
            .unwrap();
        assert_eq!(head.intent.id, second_ids[&key(site)]);
        assert!(head.completion.is_some());
    }
    assert!(!roots[0].join("old.html").exists());
    assert_eq!(snapshot(&roots[0].join(".git")), git);
    assert_eq!(
        fs::read(roots[1].join(".git")).unwrap(),
        b"gitdir: ../owner-admin\n"
    );
    second.close().expect("explicit second writer close");
}

#[test]
fn incomplete_duplicate_or_foreign_operation_ids_refuse_before_every_intent_and_output() {
    let fixture = Fixture::new(&[]);
    let parent = tempdir().expect("native outputs");
    let roots = [parent.path().join("one"), parent.path().join("other")];
    output_root(&roots[0], false);
    output_root(&roots[1], true);
    let config = destinations(
        &fixture.config(),
        &[(SELECTED[0], &roots[0]), (SELECTED[1], &roots[1])],
    );
    let acquired = sites::acquire_set(&config, &SELECTED);
    let rendered = render_set(&acquired, &SELECTED);
    let (journal, initial) = initialize();
    let mut current = writer(journal.path(), initial.header);
    for case in ["missing", "duplicate", "foreign"] {
        let mut selected_ids = ids(&SELECTED, case);
        match case {
            "missing" => {
                selected_ids.remove(&key(SELECTED[1]));
            }
            "duplicate" => {
                selected_ids.insert(key(SELECTED[1]), selected_ids[&key(SELECTED[0])]);
            }
            _ => {
                selected_ids.insert(key("site:foreign"), source::Sha256Digest::of(b"foreign"));
            }
        }
        let plan = current
            .plan_materializations(&rendered, Default::default(), options().evidence_bytes)
            .unwrap();
        let before = snapshot(parent.path());
        let database = fs::read(&initial.database).expect("before history bytes");
        let error = current
            .materialize_set(plan, &selected_ids, options())
            .expect_err("all ID bindings precede effects");
        assert_eq!(error.requested, SELECTED.map(key));
        assert!(error.completed.is_empty());
        assert!(error.failed.is_none());
        assert_eq!(error.cause.code(), "store_materialization_conflict");
        assert_eq!(snapshot(parent.path()), before);
        assert_eq!(fs::read(&initial.database).unwrap(), database);
        assert_unowned(&mut current, &[&roots[0], &roots[1]]);
    }
    current
        .close()
        .expect("no refused operation invalidated writer custody");
}

#[test]
fn overlapping_destinations_and_incomplete_render_refuse_before_any_history_append() {
    for case in ["same", "nested", "incomplete"] {
        let fixture = Fixture::new(&[]);
        let parent = tempdir().expect("output parent");
        let one = parent.path().join("one");
        output_root(&one, false);
        let other = match case {
            "same" => one.clone(),
            "nested" => {
                let path = one.join("nested");
                output_root(&path, true);
                path
            }
            _ => {
                let path = parent.path().join("other");
                output_root(&path, true);
                path
            }
        };
        let config = destinations(
            &fixture.config(),
            &[(SELECTED[0], &one), (SELECTED[1], &other)],
        );
        let acquired = sites::acquire_set(&config, &SELECTED);
        let page = "page.html".parse().unwrap();
        let alias = "alias.html".parse().unwrap();
        let model = "model.json".parse().unwrap();
        let collision = "index.html".parse().unwrap();
        let mut render_options = sites::options(&SELECTED, &page, &alias, &model);
        if case == "incomplete" {
            render_options
                .sites
                .get_mut(&key(SELECTED[0]))
                .unwrap()
                .model_output = Some(&collision);
        }
        let rendered = build::render_publications(&acquired, render_options, Default::default())
            .expect("complete requested render membership");
        if case == "incomplete" {
            assert!(!rendered.is_complete());
            assert!(rendered.sites()[&key(SELECTED[0])].is_err());
            assert!(rendered.sites()[&key(SELECTED[1])].is_ok());
        }
        let (journal, initial) = initialize();
        let mut current = writer(journal.path(), initial.header);
        let database = fs::read(&initial.database).unwrap();
        let before = snapshot(parent.path());
        let error = current
            .plan_materializations(&rendered, Default::default(), options().evidence_bytes)
            .expect_err("no writable or journaled subset");
        assert_eq!(error.requested, SELECTED.map(key));
        match error.cause {
            build::MaterializationSetPlanFailure::Output(build::OutputSetPlanFailure::Refused(
                reason,
            )) if case == "incomplete" => {
                assert_eq!(reason, "every requested site must have a complete render")
            }
            build::MaterializationSetPlanFailure::Output(build::OutputSetPlanFailure::Site {
                error:
                    build::OutputPlanError::Observation(source::DestinationError::SourceOverlap {
                        ..
                    }),
                ..
            }) if case != "incomplete" => {}
            unexpected => panic!("exact native complete-set cause: {unexpected:?}"),
        }
        assert_eq!(snapshot(parent.path()), before);
        assert_eq!(fs::read(&initial.database).unwrap(), database);
        assert_unowned(&mut current, &[&one, &other]);
        current.close().expect("refusal before native effects");
    }
}

#[test]
fn changed_second_destination_preserves_first_completion_pending_failure_and_unattempted_third() {
    let fixture = Fixture::new(&[("project/page.md", LAST.as_bytes())]);
    let parent = tempdir().expect("three disjoint outputs");
    let roots = [
        parent.path().join("one"),
        parent.path().join("other"),
        parent.path().join("last"),
    ];
    for (index, root) in roots.iter().enumerate() {
        output_root(root, index != 0);
    }
    let third = format!(
        "{}\n[[sites]]\nid='site:z-last'\npublisher='owner:one'\ndeployable=false\n\
[[brands]]\nid='brand:last'\nname='Last publication'\n\
[[brands.publications]]\nsite='site:z-last'\npublic_base_url='https://last.example/'\nauthored=[{{source='source:last',target='last'}}]\n\
[[sources]]\nid='source:last'\nlocation={{kind='repository',root={:?},commit='{}',subdirectory='project'}}\n",
        fixture.config(),
        fixture.directory.path().to_str().unwrap(),
        fixture.commit
    );
    let config = destinations(
        &third,
        &[
            (THREE[0], &roots[0]),
            (THREE[1], &roots[1]),
            (THREE[2], &roots[2]),
        ],
    );
    let acquired = sites::acquire_set(&config, &THREE);
    let rendered = render_set(&acquired, &THREE);
    assert!(rendered.is_complete());
    let third_before = snapshot(&roots[2]);
    let git = snapshot(&roots[0].join(".git"));
    let (journal, initial) = initialize();
    let mut current = writer(journal.path(), initial.header);
    let plan = current
        .plan_materializations(&rendered, Default::default(), options().evidence_bytes)
        .expect("complete original three-site plan");
    let selected_ids = ids(&THREE, "changed-second");
    fs::write(roots[1].join("user.txt"), b"owner changed after planning")
        .expect("real destination baseline drift");
    let error = current
        .materialize_set(plan, &selected_ids, options())
        .expect_err("later failure is not complete-set success");
    assert_eq!(error.requested, THREE.map(key));
    assert_eq!(error.failed, Some(key(THREE[1])));
    assert_eq!(
        error.completed.keys().cloned().collect::<Vec<_>>(),
        [key(THREE[0])]
    );
    let first = &error.completed[&key(THREE[0])];
    assert_eq!(first.history.record.intent.id, selected_ids[&key(THREE[0])]);
    assert!(first.history.record.completion.is_some());
    let output = first
        .output
        .as_ref()
        .expect("actual successful prefix read-back");
    assert_eq!(output.inventory(), &first.history.record.intent.expected);
    assert_generated(
        rendered.sites()[&key(THREE[0])].as_ref().unwrap(),
        &roots[0],
    );
    let build::MaterializationError::Write { id, cause } = &error.cause else {
        panic!("exact native failed effect phase: {:?}", error.cause);
    };
    assert_eq!(*id, selected_ids[&key(THREE[1])]);
    assert!(
        cause.attempted.is_empty(),
        "changed baseline refused before this site's first effect"
    );
    assert!(cause.residue.is_none());
    assert!(matches!(
        &cause.cause,
        source::DestinationError::Observation(source::Error::Changed(_))
    ));
    assert_eq!(snapshot(&roots[2]), third_before);
    assert_eq!(
        fs::read(roots[1].join("user.txt")).unwrap(),
        b"owner changed after planning"
    );
    assert!(!roots[1].join("model.json").exists());
    assert!(!roots[2].join("model.json").exists());
    assert_eq!(snapshot(&roots[0].join(".git")), git);
    for root in &roots[1..] {
        assert_eq!(
            fs::read(root.join(".git")).unwrap(),
            b"gitdir: ../owner-admin\n"
        );
    }
    let first_history = current
        .inspect_materialization(output.binding().canonical_root())
        .unwrap()
        .frontier;
    assert_eq!(
        first_history.head.unwrap().intent.id,
        selected_ids[&key(THREE[0])]
    );
    assert!(first_history.active.is_none());
    let second_history = current
        .inspect_materialization(
            &fs::canonicalize(&roots[1]).expect("canonical failed destination"),
        )
        .unwrap()
        .frontier;
    assert!(second_history.head.is_none());
    let pending = second_history
        .active
        .expect("intent retained before failed native write");
    assert_eq!(pending.intent.id, selected_ids[&key(THREE[1])]);
    assert!(pending.completion.is_none());
    assert_eq!(
        pending.intent.generated,
        *rendered.sites()[&key(THREE[1])]
            .as_ref()
            .unwrap()
            .site()
            .output()
            .inventory()
    );
    assert_unowned(&mut current, &[&roots[2]]);
    let expected = current.inspect().unwrap().header;
    current
        .close()
        .expect("close does not erase pending history");
    let mut reopened = writer(journal.path(), expected);
    let before = snapshot(parent.path());
    let database = fs::read(&initial.database).unwrap();
    let refused = reopened
        .plan_materializations(&rendered, Default::default(), options().evidence_bytes)
        .expect_err("pending second site blocks the entire new set");
    assert_eq!(refused.requested, THREE.map(key));
    assert!(
        matches!(refused.cause, build::MaterializationSetPlanFailure::Site { site, error } if site == key(THREE[1]) && error.code() == "store_materialization_pending")
    );
    assert_eq!(snapshot(parent.path()), before);
    assert_eq!(fs::read(&initial.database).unwrap(), database);
    reopened
        .close()
        .expect("no retry or reconciliation effects");
}
