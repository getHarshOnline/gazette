//! Independent fixed vectors and semantic sensitivity of the canonical tree identity.

use gazette_core::source::{
    Content, Inventory, InventoryBuilder, Limits, Sha256Digest, TreeIdentity,
};

fn inventory(entries: &[(&str, Content)]) -> Inventory {
    let mut builder = InventoryBuilder::new(Limits::default());
    for (path, content) in entries {
        builder
            .insert(path.parse().expect("entry path"), *content)
            .expect("entry");
    }
    builder.finish()
}

fn file(bytes: &[u8]) -> Content {
    Content::File {
        bytes: bytes.len() as u64,
        sha256: Sha256Digest::of(bytes),
    }
}

#[test]
fn fixed_vectors_pin_the_encoding_independently_of_json() {
    // Independently calculated with Perl Digest::SHA and big-endian Q> lengths,
    // not generated by this Rust implementation or serialized inventory JSON.
    for (tree, expected) in [
        (
            inventory(&[]),
            "7cf91ba08b23337630ced184a081ba7d19733bb06c4679726f60db9bdd6214e1",
        ),
        (
            inventory(&[("readme.md", file(b"abc"))]),
            "2c53e22d0ebcd3daee756bdb6f0c2227f0e8254d2f5e88a1e63e33c52a240156",
        ),
        (
            inventory(&[("empty", Content::Directory), (".hidden", file(b"abc"))]),
            "513140c1e6c293bc9ca780f7a31a6bcacabc1b7940e79c0662c1fb09fd78aca8",
        ),
    ] {
        assert_eq!(tree.identity().sha256().to_string(), expected);
        let json = serde_json::to_value(&tree).expect("inventory JSON");
        assert_eq!(json["identity"]["format"], TreeIdentity::FORMAT);
        assert_eq!(json["identity"]["sha256"], expected);
    }
}

#[test]
fn names_roles_sizes_bytes_and_empty_directory_presence_are_bound() {
    let base = inventory(&[("a", file(b"abc"))]).identity();
    for alternative in [
        inventory(&[("b", file(b"abc"))]),
        inventory(&[("A", file(b"abc"))]),
        inventory(&[("a", Content::Directory)]),
        inventory(&[("a", file(b"abd"))]),
        inventory(&[(
            "a",
            Content::File {
                bytes: 4,
                sha256: Sha256Digest::of(b"abc"),
            },
        )]),
        inventory(&[("a", file(b"abc")), ("empty", Content::Directory)]),
    ] {
        assert_ne!(base, alternative.identity());
    }
    assert_ne!(
        inventory(&[("café", file(b"abc"))]).identity(),
        inventory(&[("cafe\u{301}", file(b"abc"))]).identity()
    );
}

#[test]
fn insertion_order_does_not_change_identity_and_framing_preserves_boundaries() {
    let first = inventory(&[("a", file(b"bc")), ("ab", file(b"c"))]);
    let reversed = inventory(&[("ab", file(b"c")), ("a", file(b"bc"))]);
    assert_eq!(first.identity(), reversed.identity());
    assert_ne!(
        inventory(&[("a", file(b"bc"))]).identity(),
        inventory(&[("ab", file(b"c"))]).identity()
    );
    assert_ne!(
        inventory(&[("a", file(b""))]).identity(),
        inventory(&[("a", Content::Directory)]).identity()
    );
}

#[test]
fn identity_transport_is_strict_and_does_not_change_the_canonical_encoding() {
    let tree = inventory(&[("readme.md", file(b"abc"))]);
    let identity = serde_json::to_string(&tree.identity()).expect("identity JSON");
    assert_eq!(
        serde_json::from_str::<TreeIdentity>(&identity).expect("pin"),
        tree.identity()
    );
    let digest = tree.identity().sha256().to_string();
    for invalid in [
        format!(r#"{{"format":"gazette.inventory.v2","sha256":"{digest}"}}"#),
        format!(r#"{{"format":"gazette.inventory.v1","sha256":"{digest}","approved":true}}"#),
        format!(r#"{{"sha256":"{digest}"}}"#),
        r#"{"format":"gazette.inventory.v1","sha256":"short"}"#.into(),
        format!(
            r#"{{"format":"gazette.inventory.v1","format":"gazette.inventory.v1","sha256":"{digest}"}}"#
        ),
        format!(r#"{{"format":"gazette.inventory.v1","sha256":"{digest}","sha256":"{digest}"}}"#),
    ] {
        assert!(
            serde_json::from_str::<TreeIdentity>(&invalid).is_err(),
            "{invalid}"
        );
    }
}
