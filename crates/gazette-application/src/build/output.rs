/// Successful synchronous local write/read-back, not durable cross-process ownership.
///
/// Only materialization constructs this evidence. A prior render, matching bytes
/// or a destination marker cannot manufacture it. The caller must keep exclusive
/// local namespace control; durable persistence/recovery remains a separate step.
#[derive(Debug)]
pub struct MaterializedOutput {
    site: gazette_core::publication::Key,
    root: PathBuf,
    observation: destination::OutputObservation,
    generated: Inventory,
    protected: Vec<PathBuf>,
}
impl MaterializedOutput {
    /// Exact publication site whose bytes were materialized.
    pub fn site(&self) -> &gazette_core::publication::Key {
        &self.site
    }
    /// Configured destination bound to the successful local operation.
    pub fn root(&self) -> &Path {
        &self.root
    }
    /// Native destination identity observed through the successful writer.
    /// This is local evidence, not durable ownership or publication authority.
    pub fn binding(&self) -> &destination::OutputBinding {
        self.observation.binding()
    }
    /// Generated entries verified by that operation, excluding unrelated user files.
    pub fn generated(&self) -> &Inventory {
        &self.generated
    }
    /// Complete read-back, including preserved unrelated entries.
    pub fn inventory(&self) -> &Inventory {
        self.observation.inventory()
    }
}

/// A write-free plan bound to one retained publication and observed destination.
///
/// No marker is consulted. Replacement/removal requires a successful native
/// materialization receipt for this same site and configured destination, with every prior
/// output still present and unchanged. Shared directories are never claimed or
/// removed. A later writer must recheck the observation before its first effect.
#[derive(Debug)]
pub struct OutputPlan<'a> {
    site: gazette_core::publication::Key,
    root: PathBuf,
    observed: destination::OutputObservation,
    expected: Inventory,
    generated: &'a CapturedSource,
    changes: Vec<OutputChange>,
    protected: Vec<PathBuf>,
    limits: Limits,
}

impl OutputPlan<'_> {
    /// Private configured native location, not public publication metadata.
    pub fn root(&self) -> &Path {
        &self.root
    }
    /// Exact complete user/output tree observed, excluding protected Git administration.
    pub fn observed(&self) -> &Inventory {
        self.observed.inventory()
    }
    /// Native root and administrative identity bound to this exact observation.
    pub fn binding(&self) -> &destination::OutputBinding {
        self.observed.binding()
    }
    /// Complete intended tree, including every preserved unrelated entry.
    pub fn expected(&self) -> &Inventory {
        &self.expected
    }
    /// Retained generated bytes; a future writer must not recompile or reopen inputs.
    pub fn generated(&self) -> &CapturedSource {
        self.generated
    }
    /// Explicit transitions; identical regeneration has no changes.
    pub fn changes(&self) -> &[OutputChange] {
        &self.changes
    }

    /// Apply this exact local plan once, without recompilation or input reopening.
    ///
    /// The destination requires trusted exclusive control. Success proves exact
    /// local read-back, not durable ownership, certification or publication.
    ///
    /// # Errors
    /// Refuses missing permission or changed state; later failures preserve
    /// partial-effect evidence. Never automatically retry a consumed plan.
    pub fn materialize(
        self,
        writer: &impl gazette_ports::destination::OutputWriter,
        allow_write: bool,
    ) -> Result<MaterializedOutput, gazette_core::destination::OutputWriteError> {
        let mutation = destination::OutputMutation::new(
            &self.root,
            &self.protected,
            &self.observed,
            &self.expected,
            self.generated.as_input(),
            &self.changes,
            self.limits,
        )
        .map_err(|cause| destination::OutputWriteError {
            cause,
            attempted: Vec::new(),
            residue: None,
        })?;
        let mut generated = InventoryBuilder::new(self.limits);
        for entry in self.generated.inventory().entries() {
            generated
                .insert(entry.path.clone(), entry.content)
                .map_err(|cause| destination::OutputWriteError {
                    cause: cause.into(),
                    attempted: Vec::new(),
                    residue: None,
                })?;
        }
        let generated = generated.finish();
        let observation = writer.write_output(mutation, allow_write)?;
        if observation.inventory() != &self.expected
            || observation.binding() != self.observed.binding()
        {
            return Err(destination::OutputWriteError {
                cause: source::Error::Changed(self.root.clone()).into(),
                attempted: self
                    .changes
                    .iter()
                    .map(|change| change.path.clone())
                    .collect(),
                residue: None,
            });
        }
        Ok(MaterializedOutput {
            site: self.site,
            root: self.root,
            observation,
            generated,
            protected: self.protected,
        })
    }
}

/// Output planning fails without creating, deleting or modifying any entry.
#[derive(Debug)]
pub enum OutputPlanError {
    /// Preview-only hyperlinks cannot enter a maintained publication directory.
    Preview,
    /// No destination was configured for this publication.
    Unconfigured,
    /// Detached configuration cannot resolve a relative output location.
    Coordinate(SourceRootUnavailable),
    /// The prior materialization names another site or configured output location.
    PriorOwner,
    /// A prior generated entry was modified or removed by another actor.
    Changed(EntryPath),
    /// Generated output attempts to enter Git administration.
    Reserved(EntryPath),
    /// A generated path collides with unowned content or an ambiguous spelling.
    Collision {
        /// First observed or conflicting original spelling.
        first: EntryPath,
        /// Generated or ambiguous spelling that cannot safely coexist.
        second: EntryPath,
    },
    /// Native destination observation or source separation failed.
    Observation(destination::Error),
    /// Complete proposed output exceeds bounds or has invalid structure.
    Output(source::Error),
}

impl OutputPlanError {
    /// Stable operation diagnostic, preserving the exact lower-layer cause.
    pub fn code(&self) -> &'static str {
        match self {
            Self::Preview => "output_preview",
            Self::Unconfigured => "output_unconfigured",
            Self::Coordinate(_) => "output_coordinate",
            Self::PriorOwner => "output_prior_owner",
            Self::Changed(_) => "output_changed",
            Self::Reserved(_) => "output_reserved",
            Self::Collision { .. } => "output_collision",
            Self::Observation(_) => "output_observation",
            Self::Output(_) => "output_limit_or_structure",
        }
    }
}

impl fmt::Display for OutputPlanError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Preview => f.write_str("preview hyperlink output cannot replace maintained publication files"),
            Self::Unconfigured => f.write_str("publication has no configured output directory; no destination inferred"),
            Self::Coordinate(error) => error.fmt(f),
            Self::PriorOwner => f.write_str("prior output belongs to another site or configured destination; no generated ownership transferred"),
            Self::Changed(path) => write!(f, "prior generated output {path} changed or disappeared; preserve it and resolve the conflict before writing"),
            Self::Reserved(path) => write!(f, "generated output {path} enters Git administration; no output plan produced"),
            Self::Collision { first, second } => write!(f, "output paths {first} and {second} collide with unowned content or incompatible structure; no replacement authorized"),
            Self::Observation(error) => error.fmt(f),
            Self::Output(error) => error.fmt(f),
        }
    }
}

impl std::error::Error for OutputPlanError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Coordinate(error) => Some(error),
            Self::Observation(error) => Some(error),
            Self::Output(error) => Some(error),
            _ => None,
        }
    }
}

impl PublicationRender<'_> {
    /// Inspect the configured destination and plan only exact generated changes.
    ///
    /// The destination must exist. Missing configuration is not replaced with a
    /// temporary directory or process-directory convention. Source roots are
    /// protected, prior ownership comes only from the supplied materialization receipt,
    /// and existing user files survive in the complete intended inventory.
    /// Planning does not grant output-write or publication permission.
    ///
    /// # Errors
    /// Refuses unresolved locations, another site's prior output, unsafe roots,
    /// changed generated files, unowned collisions and exhausted aggregate bounds.
    pub fn plan_output<'a>(
        &'a self,
        reader: &impl OutputReader,
        previous: Option<&MaterializedOutput>,
        limits: Limits,
    ) -> Result<OutputPlan<'a>, OutputPlanError> {
        self.plan_output_prior(
            reader,
            previous.map(|previous| PreviousOutput {
                site: previous.site(),
                binding: previous.binding(),
                generated: previous.generated(),
                protected: &previous.protected,
                configured_root: Some(previous.root()),
            }),
            limits,
            &[],
        )
    }

    fn plan_output_prior<'a>(
        &'a self,
        reader: &impl OutputReader,
        previous: Option<PreviousOutput<'_>>,
        limits: Limits,
        extra_protected: &[PathBuf],
    ) -> Result<OutputPlan<'a>, OutputPlanError> {
        let root = self
            .inputs()
            .output_directory()
            .map_err(OutputPlanError::Coordinate)?
            .ok_or(OutputPlanError::Unconfigured)?;
        RetainedOutput {
            site: self.inputs().site(),
            root,
            generated: self.site().output(),
            protected: self.protected_roots().to_vec(),
        }
        .plan(reader, previous, limits, extra_protected)
    }
}

/// A retained artifact and its configured native coordinate; no renderer or generator handle.
pub(super) struct RetainedOutput<'a> {
    pub(super) site: &'a gazette_core::publication::Key,
    pub(super) root: PathBuf,
    pub(super) generated: &'a CapturedSource,
    pub(super) protected: Vec<PathBuf>,
}

impl<'a> RetainedOutput<'a> {
    pub(super) fn plan(
        self,
        reader: &impl OutputReader,
        previous: Option<PreviousOutput<'_>>,
        limits: Limits,
        extra_protected: &[PathBuf],
    ) -> Result<OutputPlan<'a>, OutputPlanError> {
        if let Some(previous) = previous
            && (previous.site != self.site
                || previous
                    .configured_root
                    .is_some_and(|selected| selected != self.root))
        {
            return Err(OutputPlanError::PriorOwner);
        }
        let mut protected = self.protected;
        protected.extend_from_slice(extra_protected);
        if let Some(previous) = previous {
            protected.extend_from_slice(previous.protected);
        }
        protected.sort();
        protected.dedup();
        let observed = reader
            .read_output(&self.root, &protected, limits)
            .map_err(OutputPlanError::Observation)?;
        if previous.is_some_and(|previous| previous.binding != observed.binding()) {
            return Err(OutputPlanError::PriorOwner);
        }
        let generated = self.generated;
        let (expected, changes) = reconcile(
            observed.inventory(),
            previous.map(|previous| previous.generated),
            generated.inventory(),
            limits,
        )?;
        Ok(OutputPlan {
            site: self.site.clone(),
            root: self.root,
            observed,
            expected,
            generated,
            changes,
            protected,
            limits,
        })
    }
}

/// Borrowed prior evidence is constructed only from an actual synchronous receipt
/// or the held store's independently checked completed head, never caller JSON.
#[derive(Clone, Copy)]
pub(super) struct PreviousOutput<'a> {
    site: &'a gazette_core::publication::Key,
    binding: &'a destination::OutputBinding,
    generated: &'a Inventory,
    protected: &'a [PathBuf],
    configured_root: Option<&'a Path>,
}

impl<'a> PreviousOutput<'a> {
    pub(super) fn from_materialized(previous: &'a MaterializedOutput) -> Self {
        Self {
            site: previous.site(),
            binding: previous.binding(),
            generated: previous.generated(),
            protected: &previous.protected,
            configured_root: Some(previous.root()),
        }
    }
}

fn reconcile(
    observed: &Inventory,
    previous: Option<&Inventory>,
    generated: &Inventory,
    limits: Limits,
) -> Result<(Inventory, Vec<OutputChange>), OutputPlanError> {
    let mut entries: BTreeMap<EntryPath, Content> = observed
        .entries()
        .iter()
        .map(|entry| (entry.path.clone(), entry.content))
        .collect();
    let previous: BTreeMap<&EntryPath, Content> = previous
        .into_iter()
        .flat_map(Inventory::entries)
        .map(|entry| (&entry.path, entry.content))
        .collect();
    for (&path, &content) in &previous {
        if entries.get(path) != Some(&content) {
            return Err(OutputPlanError::Changed(path.clone()));
        }
    }
    let mut names = BTreeMap::new();
    for entry in observed.entries().iter().chain(generated.entries()) {
        if entry
            .path
            .as_str()
            .split('/')
            .any(|part| part.eq_ignore_ascii_case(".git"))
        {
            return Err(OutputPlanError::Reserved(entry.path.clone()));
        }
        let name = collision_key(entry.path.as_str());
        if let Some(first) = names.insert(name, entry.path.clone())
            && first != entry.path
        {
            return Err(OutputPlanError::Collision {
                first,
                second: entry.path.clone(),
            });
        }
    }
    let desired: BTreeMap<&EntryPath, Content> = generated
        .entries()
        .iter()
        .map(|entry| (&entry.path, entry.content))
        .collect();
    // Compare kinds before scheduling removals, so deleting an old generated
    // file cannot disguise a file-to-directory transition as fresh creation.
    for entry in generated.entries() {
        if let Some(existing) = entries.get(&entry.path)
            && ((*existing == Content::Directory) != (entry.content == Content::Directory))
        {
            return Err(OutputPlanError::Collision {
                first: entry.path.clone(),
                second: entry.path.clone(),
            });
        }
    }
    let mut changes = BTreeMap::new();
    // Never remove directories: they may predate Gazette or contain unrelated files.
    for (&path, &content) in &previous {
        if matches!(content, Content::File { .. }) && !desired.contains_key(path) {
            entries.remove(path);
            changes.insert(
                path.clone(),
                OutputChange {
                    path: path.clone(),
                    before: Some(content),
                    after: None,
                },
            );
        }
    }
    for entry in generated.entries() {
        let before = entries.get(&entry.path).copied();
        if let Some(existing) = before {
            let shared_directory =
                existing == Content::Directory && entry.content == Content::Directory;
            let owned_file = matches!(
                (existing, entry.content),
                (Content::File { .. }, Content::File { .. })
            ) && previous.get(&entry.path) == Some(&existing);
            if !shared_directory && !owned_file {
                return Err(OutputPlanError::Collision {
                    first: entry.path.clone(),
                    second: entry.path.clone(),
                });
            }
        }
        entries.insert(entry.path.clone(), entry.content);
        if before != Some(entry.content) {
            changes.insert(
                entry.path.clone(),
                OutputChange {
                    path: entry.path.clone(),
                    before,
                    after: Some(entry.content),
                },
            );
        }
    }
    let mut expected = InventoryBuilder::new(limits);
    for (path, content) in entries {
        expected
            .insert(path, content)
            .map_err(OutputPlanError::Output)?;
    }
    Ok((expected.finish(), changes.into_values().collect()))
}
