//! Integrity and exact-use accounting, deliberately separate from policy acceptance.

use std::{
    collections::{BTreeMap, BTreeSet},
    fmt,
    marker::PhantomData,
};

use gazette_core::{publication::Key, source::Sha256Digest};
use serde::{
    Deserialize, Deserializer, Serialize,
    de::{MapAccess, Visitor, value::MapAccessDeserializer},
};
use serde_json::Value;

use super::{PublicationReview, ReviewUses};

/// Exact policy-source coordinate expected by the caller, not verified authority.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct ReviewPolicy {
    /// Policy projection identity; no matching by label or prefix.
    pub id: Key,
    /// Exact policy revision identifier.
    pub revision: Key,
    /// Digest of the policy source used by the responding evaluator.
    pub source_sha256: Sha256Digest,
}

/// Independent expectations supplied before consuming response bytes.
/// Computing these from the response itself proves no independent binding.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct ReviewResponseBinding {
    /// Expected policy identity, revision and source bytes.
    #[serde(deserialize_with = "named")]
    pub policy: ReviewPolicy,
    /// Exact expected response bytes, including whitespace and row order.
    pub response_sha256: Sha256Digest,
}

/// Private response bytes and independent expectations; transport is not matching or approval.
#[derive(Clone, Debug, Serialize, Deserialize, schemars::JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct ReviewSubmission {
    /// Independently selected policy coordinates and original response byte digest.
    #[serde(deserialize_with = "named")]
    pub binding: ReviewResponseBinding,
    /// Exact original response JSON, including whitespace and decision order.
    pub response_json: String,
}

/// Independent bounds on untrusted response transport and matched record count.
#[derive(Clone, Copy, Debug)]
pub struct ReviewResponseLimits {
    /// Maximum complete JSON bytes; enforced before decoding or hashing.
    pub bytes: usize,
    /// Maximum decoded decision records before matching; raw bytes bound decoding first.
    /// Each required occurrence still needs its own row.
    pub decisions: usize,
}

impl Default for ReviewResponseLimits {
    fn default() -> Self {
        Self {
            bytes: 16 << 20,
            decisions: 100_000,
        }
    }
}

/// What the responding evaluator reports, not what Gazette has authorized.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, schemars::JsonSchema)]
#[serde(rename_all = "kebab-case")]
pub enum ReviewOutcome {
    /// Reported permission requiring separate authority, evidence and freshness validation.
    Allow,
    /// A held use remains explicit; no fallback to another value is implied.
    Hold,
    /// Proposed exclusion; this does not authorize silently shrinking public output.
    Exclude,
}

impl<'de> Deserialize<'de> for ReviewOutcome {
    fn deserialize<D: Deserializer<'de>>(decoder: D) -> Result<Self, D::Error> {
        struct Outcome;
        impl Visitor<'_> for Outcome {
            type Value = ReviewOutcome;

            fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str("one of the strings allow, hold or exclude")
            }

            fn visit_str<E: serde::de::Error>(self, value: &str) -> Result<Self::Value, E> {
                match value {
                    "allow" => Ok(ReviewOutcome::Allow),
                    "hold" => Ok(ReviewOutcome::Hold),
                    "exclude" => Ok(ReviewOutcome::Exclude),
                    _ => Err(E::custom("unknown review outcome")),
                }
            }
        }
        decoder.deserialize_str(Outcome)
    }
}

/// One reported value use within an exact request; parents never stand in for children.
#[derive(Clone, Debug, Serialize, Deserialize, schemars::JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct ReviewDecision {
    /// Zero-based surface index in the digest-bound request, not a global object identity.
    pub surface: usize,
    /// Exact canonical RFC 6901 pointer generated by that surface's use iterator.
    pub pointer: String,
    /// Reported outcome for this occurrence only.
    pub outcome: ReviewOutcome,
    /// Nonempty unique policy-native evidence references; existence/trust is not inferred.
    pub evidence: Vec<Key>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Response {
    format: String,
    request_sha256: Sha256Digest,
    #[serde(deserialize_with = "named")]
    policy: ReviewPolicy,
    #[serde(deserialize_with = "named_decisions")]
    decisions: Vec<ReviewDecision>,
}

/// Closed result of matching one complete private review response.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, schemars::JsonSchema)]
pub enum ReviewResponseStatus {
    /// Integrity and coverage matched; evaluator authority remains unverified.
    #[serde(rename = "matched-unverified")]
    MatchedUnverified,
}

/// Complete response matching, not admitted publication semantics.
/// The reported outcomes retain their evidence and input order. Even an all-allow response
/// is unverified: matching does not establish evaluator authenticity, source authority,
/// evidence validity, freshness, revocation, rights, disclosure or release permission.
/// No public-rendering or release operation accepts this type as authorization.
/// The private report includes the original response text and survives the source
/// request's lifetime; the request digest is a binding, not reconstructed provenance.
#[derive(Clone, Debug, Serialize, schemars::JsonSchema)]
pub struct MatchedReviewResponse {
    status: ReviewResponseStatus,
    request_sha256: Sha256Digest,
    response_sha256: Sha256Digest,
    policy: ReviewPolicy,
    decisions: Vec<ReviewDecision>,
    response_json: String,
}

impl MatchedReviewResponse {
    pub(crate) fn policy(&self) -> &ReviewPolicy {
        &self.policy
    }

    /// Exact digest of the independently retained request used for complete occurrence matching.
    pub fn request_sha256(&self) -> Sha256Digest {
        self.request_sha256
    }

    /// Original validated response text, never reconstructed from parsed decisions.
    pub fn response_json(&self) -> &str {
        &self.response_json
    }

    /// Complete reported decisions in original response order, with no mutable access.
    pub fn decisions(&self) -> &[ReviewDecision] {
        &self.decisions
    }
}

impl PublicationReview {
    /// Match freshly captured evaluator bytes to a preselected policy and this exact review.
    /// The resulting byte digest is an observation, not an independently supplied expectation.
    pub(crate) fn match_captured_response(
        &self,
        bytes: &[u8],
        policy: &ReviewPolicy,
        limits: ReviewResponseLimits,
    ) -> Result<MatchedReviewResponse, ReviewResponseError> {
        match_captured_review_response(
            self.sha256(),
            self.request()
                .surfaces()
                .iter()
                .map(super::ReviewSurface::value),
            bytes,
            policy,
            limits,
        )
    }

    /// Match bounded response bytes to independent expectations and every requested use.
    ///
    /// No native I/O, policy execution, clock read, inference, approval or output filtering
    /// occurs. Equality binds exact values through the request digest. A surface ordinal is
    /// meaningful only inside that request; titles, pointer prefixes and wildcards cannot
    /// replace exact coverage. Hold/exclude rows remain explicit unverified outcomes.
    ///
    /// # Errors
    /// Rejects size/count limits, changed response/request/policy identity, malformed or
    /// unsupported JSON, duplicate fields/decisions, missing evidence references and any
    /// incomplete or extra coverage. Failure returns no partially matched response.
    pub fn match_response(
        &self,
        bytes: &[u8],
        binding: &ReviewResponseBinding,
        limits: ReviewResponseLimits,
    ) -> Result<MatchedReviewResponse, ReviewResponseError> {
        match_review_response(
            self.sha256(),
            self.request()
                .surfaces()
                .iter()
                .map(super::ReviewSurface::value),
            bytes,
            binding,
            limits,
        )
    }
}

// The history reader verifies retained request shape/context and its raw digest first.
// This shared matcher does not reconstruct PublicationReview or claim live provenance.
pub(crate) fn match_review_response<'a>(
    request_sha256: Sha256Digest,
    surfaces: impl IntoIterator<Item = &'a Value>,
    bytes: &[u8],
    binding: &ReviewResponseBinding,
    limits: ReviewResponseLimits,
) -> Result<MatchedReviewResponse, ReviewResponseError> {
    if bytes.len() > limits.bytes {
        return Err(ReviewResponseError::Limit("response bytes"));
    }
    let response_sha256 = Sha256Digest::of(bytes);
    if response_sha256 != binding.response_sha256 {
        return Err(ReviewResponseError::Binding("response bytes"));
    }
    match_captured_review_response(request_sha256, surfaces, bytes, &binding.policy, limits)
}

// One decoder and complete-use matcher serves imported and checker-produced responses.
// Only the imported caller can assert an independently known response-byte digest.
pub(crate) fn match_captured_review_response<'a>(
    request_sha256: Sha256Digest,
    surfaces: impl IntoIterator<Item = &'a Value>,
    bytes: &[u8],
    policy: &ReviewPolicy,
    limits: ReviewResponseLimits,
) -> Result<MatchedReviewResponse, ReviewResponseError> {
    if bytes.len() > limits.bytes {
        return Err(ReviewResponseError::Limit("response bytes"));
    }
    let response_sha256 = Sha256Digest::of(bytes);
    let response_json = std::str::from_utf8(bytes).map_err(|_| {
        ReviewResponseError::Json(serde::de::Error::custom("invalid UTF-8 response"))
    })?;
    let Named(response): Named<Response> =
        serde_json::from_str(response_json).map_err(ReviewResponseError::Json)?;
    if response.format != "gazette-review-response/1" {
        return Err(ReviewResponseError::Format);
    }
    if response.request_sha256 != request_sha256 {
        return Err(ReviewResponseError::Binding("review request"));
    }
    if &response.policy != policy {
        return Err(ReviewResponseError::Binding(
            "policy identity/revision/source",
        ));
    }
    if response.decisions.len() > limits.decisions {
        return Err(ReviewResponseError::Limit("decision records"));
    }
    // Borrow only the address keys; response rows retain their original order and data.
    let mut pending = BTreeMap::<usize, BTreeSet<&str>>::new();
    for (index, decision) in response.decisions.iter().enumerate() {
        if decision.evidence.is_empty()
            || decision.evidence.iter().collect::<BTreeSet<_>>().len() != decision.evidence.len()
        {
            return Err(ReviewResponseError::Evidence { decision: index });
        }
        if !pending
            .entry(decision.surface)
            .or_default()
            .insert(decision.pointer.as_str())
        {
            return Err(ReviewResponseError::Duplicate { decision: index });
        }
    }
    for (surface, projection) in surfaces.into_iter().enumerate() {
        let mut decisions = pending
            .remove(&surface)
            .ok_or(ReviewResponseError::Coverage { surface })?;
        for usage in ReviewUses::new(projection) {
            if !decisions.remove(usage.pointer.as_str()) {
                return Err(ReviewResponseError::Coverage { surface });
            }
        }
        if !decisions.is_empty() {
            return Err(ReviewResponseError::Coverage { surface });
        }
    }
    if let Some((surface, _)) = pending.first_key_value() {
        return Err(ReviewResponseError::Coverage { surface: *surface });
    }
    Ok(MatchedReviewResponse {
        status: ReviewResponseStatus::MatchedUnverified,
        request_sha256,
        response_sha256,
        policy: response.policy,
        decisions: response.decisions,
        response_json: response_json.to_owned(),
    })
}

// Struct deserialization alone also accepts positional arrays. These adapters retain
// serde's duplicate/unknown-field checks while requiring named objects at each boundary.
struct Named<T>(T);

impl<'de, T: Deserialize<'de>> Deserialize<'de> for Named<T> {
    fn deserialize<D: Deserializer<'de>>(decoder: D) -> Result<Self, D::Error> {
        named(decoder).map(Self)
    }
}

fn named<'de, T: Deserialize<'de>, D: Deserializer<'de>>(decoder: D) -> Result<T, D::Error> {
    struct Object<T>(PhantomData<fn() -> T>);
    impl<'de, T: Deserialize<'de>> Visitor<'de> for Object<T> {
        type Value = T;

        fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
            f.write_str("a named review object")
        }

        fn visit_map<M: MapAccess<'de>>(self, map: M) -> Result<Self::Value, M::Error> {
            T::deserialize(MapAccessDeserializer::new(map))
        }
    }
    decoder.deserialize_map(Object(PhantomData))
}

fn named_decisions<'de, D: Deserializer<'de>>(decoder: D) -> Result<Vec<ReviewDecision>, D::Error> {
    Vec::<Named<ReviewDecision>>::deserialize(decoder)
        .map(|rows| rows.into_iter().map(|Named(row)| row).collect())
}

/// No complete exact response was established. Display omits reported private values;
/// native JSON diagnostics in the source chain remain private operator evidence.
#[derive(Debug)]
pub enum ReviewResponseError {
    /// The selected native evaluator did not complete with a normal zero exit.
    Exit,
    /// Complete reported decisions include a hold or exclusion; no implicit set repair.
    Disposition,
    /// Complete input or record count exceeded its declared allowance.
    Limit(&'static str),
    /// Exact response, request or policy coordinates disagree.
    Binding(&'static str),
    /// Native strict JSON/schema failure; no permissive value-map decoding is used.
    Json(serde_json::Error),
    /// Unsupported response encoding identity.
    Format,
    /// A use occurred more than once, even if reported outcomes agree.
    Duplicate {
        /// Index of the later response row.
        decision: usize,
    },
    /// A row's evidence references are empty or repeated.
    Evidence {
        /// Exact response row index, not a guessed source location.
        decision: usize,
    },
    /// Missing or extra exact occurrence; no pointer normalization or parent fallback.
    Coverage {
        /// Request surface index involved, or the supplied out-of-range index.
        surface: usize,
    },
}

impl ReviewResponseError {
    /// Stable response-matching class, not a policy approval result.
    pub fn code(&self) -> &'static str {
        match self {
            Self::Exit => "publication_review_response_exit",
            Self::Disposition => "publication_review_response_disposition",
            Self::Limit(_) => "publication_review_response_limit",
            Self::Binding(_) => "publication_review_response_binding",
            Self::Json(_) => "publication_review_response_json",
            Self::Format => "publication_review_response_format",
            Self::Duplicate { .. } => "publication_review_response_duplicate",
            Self::Evidence { .. } => "publication_review_response_evidence",
            Self::Coverage { .. } => "publication_review_response_coverage",
        }
    }
}

impl fmt::Display for ReviewResponseError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Exit => f.write_str("candidate evaluator did not return a normal zero exit"),
            Self::Disposition => f.write_str("candidate evaluator held or excluded an exact use"),
            Self::Limit(resource) => write!(f, "review response exceeds {resource} allowance"),
            Self::Binding(coordinate) => {
                write!(f, "review response differs from expected {coordinate}")
            }
            // Parser text may quote untrusted private fields or values; expose coordinates only.
            Self::Json(error) => write!(
                f,
                "invalid review response JSON/schema at line {}, column {}",
                error.line(),
                error.column()
            ),
            Self::Format => {
                f.write_str("unsupported review response format; use gazette-review-response/1")
            }
            Self::Duplicate { decision } => {
                write!(f, "review response row {decision} repeats an exact use")
            }
            Self::Evidence { decision } => write!(
                f,
                "review response row {decision} requires nonempty unique evidence references"
            ),
            Self::Coverage { surface } => write!(
                f,
                "review response does not exactly cover surface {surface}; supply every occurrence once"
            ),
        }
    }
}

impl std::error::Error for ReviewResponseError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Json(error) => Some(error),
            _ => None,
        }
    }
}
